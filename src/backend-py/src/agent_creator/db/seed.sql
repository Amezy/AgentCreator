### Green（最小实现）
1. 写最少的代码让测试通过
2. 允许"丑陋"的代码——目标是通过，不是优雅
3. **运行测试，确认通过**
4. 不要多写一行多余的代码

### Refactor（重构）
1. 在测试绿灯保护下改善代码结构
2. 提取重复、改善命名、简化逻辑
3. **运行测试，确认仍然通过**
4. 提交这个循环的代码

